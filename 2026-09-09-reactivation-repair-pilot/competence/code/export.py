def export(root, analysis, destination, *, prior_root, forbidden_literals=()):
    root, analysis, destination = Path(root).resolve(), Path(analysis).resolve(), Path(destination).resolve()
    require(not destination.exists(), 'Export destination must not exist')
    require((root / TERMINAL).is_file(), 'Actual reviewed competence-scope completion is required')
    completion = read(root / TERMINAL)
    require(completion.get('status') == 'complete' and completion.get('outcome') == SCOPE_OUTCOME,
            'Actual reviewed competence-scope completion is required')
    require(completion.get('synthetic_fixture') is not True, 'Synthetic fixtures cannot be exported as actual results')
    require(len(completion['completed_stages']) == 58 and completion['selected_installations'] == {},
            'Expected exactly the retained competence scope, with no conditional installation')
    require(completion['original_terminal']['route'] in ('original_numerical_stop', 'administrative_guard_reached'),
            'Unreviewed original termination route')
    checked = read(analysis / 'COMPLETED.json')
    require(checked.get('status') == 'complete' and checked.get('synthetic_fixture') is not True,
            'Completed actual CPU scope analysis is required')
    require(checked.get('root_terminal_path') == TERMINAL
            and checked['root_program_completion_sha256'] == sha(root / TERMINAL),
            'Analysis belongs to another competence-scope terminal')
    require(checked.get('projection_used') is False, 'Production export requires original-byte local analysis')
    for relative, digest in checked['checked_input_sha256'].items():
        require(sha(safe(root, relative)) == digest, 'Analyzed original input changed: ' + relative)
    for relative, digest in checked['artifacts_sha256'].items():
        require(sha(safe(analysis, relative)) == digest, 'Completed analysis artifact changed: ' + relative)
    tools = root / TOOLS
    require(sha(tools / 'analyze.py') == checked['analyzer_sha256']
            and sha(tools / 'scope_support.py') == checked['scope_support_sha256']
            and sha(tools / 'qualitative_plan.json') == checked['qualitative_plan_sha256'],
            'Scope analysis utilities differ from completed analysis')
    analysis_freeze = read(tools / 'IMPLEMENTATION_FREEZE.json')
    for relative, digest in analysis_freeze['files_sha256'].items():
        require(sha(safe(root, relative)) == digest, 'Frozen scope utility differs: ' + relative)
    snapshot = completion['source_snapshot']
    freeze = read(root / 'results/FROZEN_PROGRAM.json')
    require(sha(root / 'results/FROZEN_PROGRAM.json') == completion['freeze_sha256']
            and read(safe(root, snapshot + '/manifest.json')) == freeze and freeze['pins'] == completion['pins'],
            'Original scientific freeze differs')
    private = tuple(forbidden_literals) + (socket.gethostname(),)
    destination.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='competence-scope-public-export-') as temporary:
        bundle = Bundle(Path(temporary) / 'entry', private)
        for relative, digest in completion['pins'].items():
            if not relative.startswith('data/'):
                bundle.exact(root, snapshot + '/' + relative, 'code/frozen/' + relative, digest)
            elif not relative.endswith('.jsonl'):
                bundle.exact(root, relative, 'code/' + relative, digest)
        bundle.exact(root, snapshot + '/manifest.json', 'code/frozen/manifest.json')
        # Every analyzer-accessed authoritative non-data artifact is retained,
        # including actual terminal/attempt/guard/amendment/review/helper records.
        for logical, digest in checked['checked_input_sha256'].items():
            if logical.startswith('data/') and logical.endswith('.jsonl'):
                continue
            if logical in bundle.files:
                require(bundle.files[logical]['original_sha256'] == digest, 'Duplicate input identity differs')
                continue
            require(not logical.endswith('.safetensors'), 'Weights must not enter analysis input transports')
            payload = safe(root, logical).read_bytes()
            require(sha_bytes(payload) == digest, 'Analyzed input drifted while packaging: ' + logical)
            public = 'results/evidence/' + logical
            if logical.endswith('/outputs.jsonl'):
                payload, details = project_outputs(payload)
                bundle.projected[logical] = details
                bundle.put(logical, public, payload, original_sha256=digest, compress=True)
            elif logical == 'results/program.jsonl':
                payload, details = project_events(payload)
                bundle.projected[logical] = details
                bundle.put(logical, public, payload, original_sha256=digest)
            else:
                bundle.put(logical, public, payload, original_sha256=digest)
        require(TERMINAL in bundle.files and completion['original_terminal']['path'] in bundle.files,
                'Authoritative scope/original termination records were not checked by analysis')
        omitted_weights = {}
        for stage in completion['completed_stages']:
            logical = stage['output']
            contract = read(safe(root, logical + '/COMPLETED.json'))
            require(bundle.files[logical + '/COMPLETED.json']['original_sha256'] == stage['completion_sha256'],
                    'Stage completion is missing or differs')
            for name, digest in contract['artifacts_sha256'].items():
                relative = logical + '/' + name
                if name.endswith('/adapter_model.safetensors'):
                    omitted_weights[relative] = digest
                else:
                    require(relative in bundle.files and bundle.files[relative]['original_sha256'] == digest,
                            'Stage nonweight artifact is missing from analysis checks')
        projection = {'version': 1,
            'scope': 'Only token IDs and operational argv omitted; original raw bytes are not reconstructed.',
            'files': bundle.projected}
        bundle.put('PUBLIC_PROJECTION.json', 'results/PUBLIC_PROJECTION.json', encoded(projection), compress=True)
        bundle.put('PUBLIC_PRIOR_BACKGROUND.json', 'background/prior_competence.json', encoded(prior_background(prior_root)))
        for relative in analysis_freeze['files_sha256']:
            if relative.startswith(TOOLS + '/'):
                name = relative.removeprefix(TOOLS + '/')
                bundle.put('__analysis__/' + name, 'code/analysis/' + name, safe(root, relative).read_bytes())
        bundle.put('__analysis__/IMPLEMENTATION_FREEZE.json', 'code/analysis/IMPLEMENTATION_FREEZE.json',
                   (tools / 'IMPLEMENTATION_FREEZE.json').read_bytes())
        bundle.put('__analysis__/COMPLETED.json', 'results/original_scope_analysis_completion.json',
                   (analysis / 'COMPLETED.json').read_bytes())
        for name in ('analysis.json', 'factorial_cells.csv', 'factorial_effects.csv', 'training_budgets.csv'):
            path = analysis / name
            if path.is_file():
                bundle.put('__analysis__/' + name, 'results/analysis/' + name, path.read_bytes(), compress=name == 'analysis.json')
        from review_packet import add_packet
        packet = add_packet(bundle, root)
        for name in ('replay.py', 'export.py', 'public_notebook.py', 'review_packet.py', 'review_replay.py'):
            bundle.put('__publication__/' + name, 'code/' + name, (HERE / name).read_bytes())
        environment_path = root / 'results/model_environment.json'
        environment = read(environment_path)
        public_environment = {'scope': 'Observed versions, not a demonstrated complete GPU environment rebuild.',
            'machine': 'dgx-spark', 'source_record_sha256': sha(environment_path),
            'versions': {name: environment[name] for name in ('python', 'torch', 'transformers', 'peft', 'bitsandbytes')}}
        bundle.put('__publication__/model_environment.json', 'code/model_environment.json', encoded(public_environment))
        bundle.put('__publication__/README.md', 'code/README.md', PUBLIC_README.encode())
        bundle.put('__publication__/.gitignore', '.gitignore', b'.venv/\n__pycache__/\n*.pyc\nreplay_output/\nregenerated_data/\n')
        manifest = {'schema': SCHEMA, 'entry_name': ENTRY, 'scope_outcome': completion['outcome'],
            'root_terminal_path': TERMINAL, 'original_scope_completion_sha256': sha(root / TERMINAL),
            'original_terminal': completion['original_terminal'],
            'original_analysis_completion_sha256': sha(analysis / 'COMPLETED.json'),
            'source_snapshot': snapshot, 'files': bundle.files,
            'regenerated_data_sha256': {k:v for k,v in completion['pins'].items() if k.startswith('data/')},
            'cohorts': {}, 'omitted_weight_identities': omitted_weights,
            'early_review_packet_sha256': bundle.files['__review__/REVIEW_PACKET.json']['decoded_sha256'],
            'sanitization': {'generated_fields_removed': ['token_ids'], 'event_fields_removed': ['argv'],
                'source_code': 'Original scientific source and separate scope-analysis source remain exact.',
                'private_literal_checks': len(private), 'automatic_scan': 'passed',
                'max_public_file_bytes': MAX_PUBLIC_FILE},
            'replay_scope': 'Entire amended-scope scientific JSON; no fabricated original completion, tokens, weights or conditional result.'}
        manifest_payload = encoded(manifest)
        scan(manifest_payload, 'PUBLIC_BUNDLE.json', private)
        require(len(manifest_payload) <= MAX_PUBLIC_FILE, 'Public bundle manifest exceeds compact artifact ceiling')
        (bundle.destination / 'results/PUBLIC_BUNDLE.json').write_bytes(manifest_payload)
        shutil.copytree(bundle.destination, destination)
    return manifest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, required=True)
    parser.add_argument('--analysis', type=Path, required=True)
    parser.add_argument('--destination', type=Path, required=True)
    parser.add_argument('--prior-root', type=Path, required=True)
    parser.add_argument('--forbid-file', type=Path, help='Private literal denylist; never copied')
    args = parser.parse_args()
    literals = args.forbid_file.read_text().splitlines() if args.forbid_file else []
    manifest = export(args.root, args.analysis, args.destination, prior_root=args.prior_root, forbidden_literals=literals)
    print(json.dumps({'status': 'exported_for_review', 'scope_outcome': manifest['scope_outcome'],
                      'original_route': manifest['original_terminal']['route'], 'files': len(manifest['files']),
                      'publication_status': 'Not committed or pushed; replay and editorial review still required.'}, indent=2))


if __name__ == '__main__':
    main()
