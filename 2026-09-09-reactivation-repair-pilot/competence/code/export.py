def require(condition, message):
    if not condition:
        raise ValueError(message)


def sha_bytes(value):
    return hashlib.sha256(value).hexdigest()


def sha(path):
    with Path(path).open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest()


def canonical(value):
    return json.dumps(value, sort_keys=True, separators=(',', ':'), ensure_ascii=False, allow_nan=False)


def encoded(value):
    return (json.dumps(value, indent=2, ensure_ascii=False, allow_nan=False) + '\n').encode()


def unique_object(pairs):
    result = {}
    for key, value in pairs:
        require(key not in result, 'Duplicate JSON key')
        result[key] = value
    return result


def loads(value):
    def reject(constant):
        raise ValueError('Nonfinite JSON constant: ' + constant)
    return json.loads(value, object_pairs_hook=unique_object, parse_constant=reject)


def read(path):
    return loads(Path(path).read_bytes())


def safe(root, relative):
    require(isinstance(relative, str) and not Path(relative).is_absolute() and '..' not in Path(relative).parts,
            'Unsafe relative artifact path')
    root = Path(root).resolve()
    result = root / relative
    require(result.resolve().is_relative_to(root), 'Artifact escapes its root')
    require(not result.is_symlink(), 'Symlink artifacts cannot be exported')
    return result


def scan(payload, label, forbidden_literals=()):
    text = payload.decode('utf-8')
    require(FORBIDDEN.search(text) is None, 'Sanitization stop in ' + label)
    for literal in forbidden_literals:
        require(not literal or literal not in text, 'Private operational identity detected in ' + label)


def project_outputs(payload):
    rows, originals = [], []
    for line in payload.splitlines():
        if not line.strip():
            continue
        row = loads(line)
        require(set(row) == {'id', 'source_row_sha256', 'rendered_row_sha256', 'generated', 'parsed'},
                'Unknown output schema must receive an explicit projection review')
        detail = row['generated']
        require(set(detail) == {'text', 'token_ids', 'generated_tokens', 'finish_reason'},
                'Unknown generation fields must receive an explicit projection review')
        require(type(detail['text']) is str and detail['finish_reason'] in ('eos', 'length'), 'Invalid generation detail')
        require(type(detail['generated_tokens']) is int and 0 < detail['generated_tokens'] <= 192,
                'Invalid generation length')
        require(len(detail['token_ids']) == detail['generated_tokens'] and
                all(type(token) is int and token >= 0 for token in detail['token_ids']), 'Invalid recorded token list')
        originals.append(sha_bytes(canonical(row).encode()))
        projected = deepcopy(row)
        del projected['generated']['token_ids']
        rows.append(projected)
    require(rows and len({r['id'] for r in rows}) == len(rows), 'Empty or duplicate output coverage')
    payload_out = ''.join(canonical(row) + '\n' for row in rows).encode()
    return payload_out, {'original_sha256': sha_bytes(payload), 'projected_sha256': sha_bytes(payload_out),
        'operation': 'omit_generated_token_ids', 'removed_fields': ['generated.token_ids'],
        'row_original_sha256': originals}


def project_events(payload):
    rows = [loads(line) for line in payload.splitlines() if line.strip()]
    require(rows and all(isinstance(row, dict) and 'event' in row for row in rows), 'Invalid program event stream')
    for row in rows:
        row.pop('argv', None)
    output = ''.join(canonical(row) + '\n' for row in rows).encode()
    return output, {'original_sha256': sha_bytes(payload), 'projected_sha256': sha_bytes(output),
                    'operation': 'omit_operational_argv', 'removed_fields': ['argv']}


class Bundle:
    def __init__(self, destination, forbidden_literals=()):
        self.destination = Path(destination)
        self.destination.mkdir(parents=True, exist_ok=False)
        self.files, self.projected = {}, {}
        self.forbidden_literals = tuple(forbidden_literals)

    def put(self, logical, public, payload, *, original_sha256=None, compress=False):
        require(logical not in self.files, 'Duplicate logical export path: ' + logical)
        scan(payload, public, self.forbidden_literals)
        if compress or len(payload) > 128_000:
            public += '.gz'
            transport, codec = gzip.compress(payload, mtime=0), 'gzip'
        else:
            transport, codec = payload, 'identity'
        require(len(transport) <= MAX_PUBLIC_FILE, 'Public file exceeds compact-artifact ceiling: ' + public)
        destination = safe(self.destination, public)
        destination.parent.mkdir(parents=True, exist_ok=True)
        with destination.open('xb') as stream:
            stream.write(transport)
        self.files[logical] = {'path': public, 'codec': codec, 'bytes': len(transport),
                              'sha256': sha_bytes(transport), 'decoded_sha256': sha_bytes(payload),
                              'decoded_bytes': len(payload),
                              'original_sha256': original_sha256 or sha_bytes(payload)}

    def exact(self, root, logical, public, expected=None):
        payload = safe(root, logical).read_bytes()
        require(expected is None or sha_bytes(payload) == expected, 'Original artifact hash differs: ' + logical)
        self.put(logical, public, payload)


def prior_background(root):
    """Reparse the completed predecessor's four calibration passes, then summarize."""
    root = Path(root)
    completion = read(root / 'results/PROGRAM_COMPLETED.json')
    require(completion['outcome'] == 'feasibility_gate_failed' and len(completion['completed_stages']) == 7,
            'Unexpected predecessor outcome; background needs explicit review')
    snapshot = safe(root, completion['source_snapshot'])
    task_path = snapshot / 'scripts/task.py'
    require(sha(task_path) == completion['pins']['scripts/task.py'], 'Prior oracle identity differs')
    spec = importlib.util.spec_from_file_location('prior_public_oracle', task_path)
    task = importlib.util.module_from_spec(spec)
    bytecode = sys.dont_write_bytecode
    sys.dont_write_bytecode = True
    try:
        spec.loader.exec_module(task)
    finally:
        sys.dont_write_bytecode = bytecode
    data_path = root / 'data/calibration.jsonl'
    require(sha(data_path) == completion['pins']['data/calibration.jsonl'], 'Prior calibration identity differs')
    cases = [loads(line) for line in data_path.read_bytes().splitlines() if line.strip()]
    trajectory = []
    for stage in completion['completed_stages']:
        directory = safe(root, stage['output'])
        contract = read(directory / 'COMPLETED.json')
        require(sha(directory / 'COMPLETED.json') == stage['completion_sha256'], 'Prior stage completion differs')
        if contract['mode'] != 'generate':
            continue
        output = directory / 'outputs.jsonl'
        require(sha(output) == contract['artifacts_sha256']['outputs.jsonl'], 'Prior raw output identity differs')
        rows = [loads(line) for line in output.read_bytes().splitlines() if line.strip()]
        require([r['id'] for r in rows] == [r['id'] for r in cases], 'Prior output coverage differs')
        counts = {g: {'n': 0, 'full_correct': 0, 'format_valid': 0, 'decision_correct': 0,
                      'false_clear': 0, 'false_report': 0} for g in ('all', 'target', 'report_control', 'clear_control')}
        for case, row in zip(cases, rows):
            require(row['source_row_sha256'] == sha_bytes(canonical(case).encode()), 'Prior source-row identity differs')
            parsed = task.parse_output(row['generated']['text'], case)
            require(parsed == row['parsed'], 'Prior saved parse differs')
            answer = parsed['parsed'] if isinstance(parsed['parsed'], dict) else {}
            gold = task.gold(case)
            group = 'clear_control' if gold['decision'] == 'CLEAR' else 'target' if task.is_trigger(case) else 'report_control'
            for name in ('all', group):
                counts[name]['n'] += 1
                for metric in ('full_correct', 'format_valid', 'decision_correct'):
                    counts[name][metric] += int(parsed[metric])
                counts[name]['false_clear'] += int(gold['decision'] == 'REPORT' and answer.get('decision') == 'CLEAR')
                counts[name]['false_report'] += int(gold['decision'] == 'CLEAR' and answer.get('decision') == 'REPORT')
        trajectory.append({'stage': stage['name'], 'completion_sha256': stage['completion_sha256'],
                           'outputs_sha256': sha(output), 'counts': counts})
    require(len(trajectory) == 4, 'Prior trajectory is incomplete')
    return {'scope': 'Compact background from the separate closed prerequisite study; no new-study results.',
        'date': '2026-09-10', 'machine': 'dgx-spark', 'outcome': completion['outcome'],
        'reason': completion['reason'], 'source_program_completion_sha256': sha(root / 'results/PROGRAM_COMPLETED.json'),
        'source_pins': completion['pins'], 'calibration_trajectory': trajectory,
        'training': {'installation': 1729, 'blocks': 3, 'updates_per_block': 96, 'unique_cases': 1536,
                     'report_cases': 1024, 'clear_cases': 512, 'learning_rate': .0001},
        'induction_runs': 0, 'repair_runs': 0, 'heldout_evaluation_runs': 0,
        'interpretation': 'No competent candidate passed all fixed gates. This supplies no repair effect, null, or equivalence estimate.'}


